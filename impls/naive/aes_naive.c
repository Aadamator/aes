// SubBytes transformation: Each byte is replaced by its corresponding value in the S-box
void SubBytes(uint8_t state[4][4]) {
    for (int i = 0; i < 4; i++){
        for (int j = 0; j < 4; j++){
            state[i][j] = sbox[state[i][j]];
            //printf("0x%02x ", state[i][j]);
        }
    }
}

// Inverse SubBytes transformation: Each byte is replaced by its corresponding value in the inverse S-box
void invSubBytes(uint8_t state[4][4]) {
    for (int i = 0; i < 4; i++){
        for (int j = 0; j < 4; j++){
            state[i][j] = inv_sbox[state[i][j]];
        }
    }
}

// ShiftRows transformation: Each row is shifted to the left by its row index
void ShiftRows(uint8_t state[4][4]) {

    // Row 0: No shift

    // Row 1: Shift left by 1
    uint8_t tmp = state[1][0];
    state[1][0] = state[1][1]; state[1][1] = state[1][2]; state[1][2] = state[1][3]; state[1][3] = tmp;

    // Row 2: Shift left by 2
    tmp = state[2][0];
    state[2][0] = state[2][2]; state[2][2] = tmp; 
    tmp = state[2][1];
    state[2][1] = state[2][3]; state[2][3] = tmp;

    // Row 3: Shift left by 3
    tmp = state[3][0];
    state[3][0] = state[3][3]; state[3][3] = state[3][2]; state[3][2] = state[3][1]; state[3][1] = tmp;
}

// Inverse ShiftRows transformation: Each row is shifted to the right by its row index
void invShiftRows(uint8_t state[4][4]) {

    // Row 0: No shift

    // Row 1: Shift right by 1
    uint8_t tmp = state[1][3];
    state[1][3] = state[1][2]; state[1][2] = state[1][1]; state[1][1] = state[1][0]; state[1][0] = tmp;

    // Row 2: Shift right by 2
    tmp = state[2][0];
    state[2][0] = state[2][2]; state[2][2] = tmp; 
    tmp = state[2][1];
    state[2][1] = state[2][3]; state[2][3] = tmp;

    // Row 3: Shift right by 3
    tmp = state[3][0];
    state[3][0] = state[3][1]; state[3][1] = state[3][2]; state[3][2] = state[3][3]; state[3][3] = tmp;
}


// xtime function: Perform multiplipilcation in GF(2^8)
uint8_t xtime(uint8_t x) {
    return ((x << 1) ^ (((x >> 7) & 1) * 0x1b));
}

// MixColumns transformation: Each column is mixed using a specific transformation
void MixColumns(uint8_t state[4][4]) {
    uint8_t temp[4][4];
    //memcpy(temp, state, sizeof(temp));
    for(int i = 0; i < 4; i++){
        temp[0][i] = xtime(state[0][i]) ^ (xtime(state[1][i]) ^ state[1][i]) ^ state[2][i] ^ state[3][i];
        temp[1][i] = state[0][i] ^ xtime(state[1][i]) ^ (xtime(state[2][i]) ^ state[2][i]) ^ state[3][i];
        temp[2][i] = state[0][i] ^ state[1][i] ^ xtime(state[2][i]) ^ (xtime(state[3][i]) ^ state[3][i]);
        temp[3][i] = (xtime(state[0][i]) ^ state[0][i]) ^ state[1][i] ^ state[2][i] ^ xtime(state[3][i]);
    
    }
    memcpy(state, temp, sizeof(temp));
}

// Inverse MixColumns transformation: Each column is mixed using the inverse transformation
void invMixColumns(uint8_t state[4][4]) {
    uint8_t temp[4][4];
    #define M2(x) (xtime(x))
    #define M4(x) (xtime(M2(x)))
    #define M8(x) (xtime(M4(x)))
    for(int i = 0; i < 4; i++){
        temp[0][i] = (M8(state[0][i]) ^ M4(state[0][i]) ^ M2(state[0][i])) ^ (M8(state[1][i]) ^ M2(state[1][i]) ^ state[1][i]) ^ (M8(state[2][i]) ^ M4(state[2][i]) ^ state[2][i]) ^ (M8(state[3][i]) ^ state[3][i]);
        temp[1][i] = (M8(state[0][i]) ^ state[0][i]) ^ (M8(state[1][i]) ^ M4(state[1][i]) ^ M2(state[1][i])) ^ (M8(state[2][i]) ^ M2(state[2][i]) ^ state[2][i]) ^ (M8(state[3][i]) ^ M4(state[3][i]) ^ state[3][i]);
        temp[2][i] = (M8(state[0][i]) ^ M4(state[0][i]) ^ state[0][i]) ^ (M8(state[1][i]) ^ state[1][i]) ^ (M8(state[2][i]) ^ M4(state[2][i]) ^ M2(state[2][i])) ^ (M8(state[3][i]) ^ M2(state[3][i]) ^ state[3][i]);
        temp[3][i] = (M8(state[0][i]) ^ M2(state[0][i]) ^ state[0][i]) ^ (M8(state[1][i]) ^ M4(state[1][i]) ^ state[1][i]) ^ (M8(state[2][i]) ^ state[2][i]) ^ (M8(state[3][i]) ^ M4(state[3][i]) ^ M2(state[3][i]));
    }
    memcpy(state, temp, sizeof(temp));
    // 9 = M8 ^ M1
    // b = 11 = M8 ^ M2 ^ M1
    // d = 13 = M8 ^ M4 ^ M1
    // e = 14 = M8 ^ M4 ^ M2
}

// AddRoundKey transformation: Each byte of the state is XORed with the corresponding byte of the round key
void AddRoundKey(uint8_t state[4][4], uint8_t roundKey[4][4]) {
    for (int i = 0; i < 4; i++){
        for (int j = 0; j < 4; j++){
            state[i][j] ^= roundKey[i][j];
            //printf("0x%02x ", state[i][j]);
        }
    }
}

// Helper function to load a 16-byte input into the state array in column-major order
void loadState(uint8_t state[4][4], const uint8_t *input_1d) {
    for (int col = 0; col < 4; col++) {
        for (int row = 0; row < 4; row++) {
            state[row][col] = input_1d[col * 4 + row];
        }
    }
}

// Helper function to print the state array in a readable format
void printState(uint8_t state[4][4]) {
    for (int row = 0; row < 4; row++) {
        for (int col = 0; col < 4; col++) {
            printf("%02x ", state[row][col]);
        }
        printf("\n");
    }
    printf("\n");
}

// Helper function to verify if the decrypted state matches the original plaintext
int verifyRoundTrip(uint8_t state[4][4], uint8_t *originalPlaintext) {
    for (int col = 0; col < 4; col++){
        for (int row = 0; row < 4; row++){
            if (state[row][col] != originalPlaintext[col*4+row]){
                return 0; // fail
            }
        }
    }
    return 1; // Success
} 

void encrypt(uint8_t state[4][4], uint8_t roundKeys[11][4][4]) {
    // Initial AddRoundKey
    AddRoundKey(state, roundKeys[0]);

    // 9 Main Rounds
    for (int i = 1; i <= 9; i++){
        SubBytes(state);
        ShiftRows(state);
        MixColumns(state);
        AddRoundKey(state, roundKeys[i]);
    }

    // Final Round (without MixColumns)
    SubBytes(state);
    ShiftRows(state);
    AddRoundKey(state, roundKeys[10]);
}

void decrypt(uint8_t state[4][4], uint8_t roundKeys[11][4][4]) {
    // Initial AddRoundKey
    AddRoundKey(state, roundKeys[10]);

    // 9 Main Rounds
    for (int i = 9; i >= 1; i--){
        invShiftRows(state);
        invSubBytes(state);
        AddRoundKey(state, roundKeys[i]);
        invMixColumns(state);
    }

    // Final Round (without invMixColumns)
    invShiftRows(state);
    invSubBytes(state);
    AddRoundKey(state, roundKeys[0]);
}

// Benchmarking function to measure the time taken for encryption of multiple blocks
void benchmark(uint8_t plaintext[16], uint8_t roundKeys[11][4][4]) {
    LARGE_INTEGER frequency;
    LARGE_INTEGER start, end;
    uint8_t state[4][4];
    int iterations = 100000;

    QueryPerformanceFrequency(&frequency);

    QueryPerformanceCounter(&start);

    for (int i = 0; i < iterations; i++) {
        loadState(state,plaintext);
        encrypt(state, roundKeys);
    }

    QueryPerformanceCounter(&end);

    double interval = (double)(end.QuadPart - start.QuadPart) / frequency.QuadPart;

    printf("Total time: %f seconds\n", interval);
    printf("Microseconds per block: %f\n", (interval / iterations) * 1000000.0);    // unit conversion to microseconds

}

// Benchmarking function to measure the CPU cycles taken for encryption of multiple blocks using __rdtscp
// ONLY ON x86/x64 ARCHITECTURES WITH SUPPORT FOR RDTSCP INSTRUCTION
void benchmarkCycles(uint8_t state[4][4], uint8_t roundKeys[11][4][4]) {
    unsigned int ui;
    unsigned long long start, end;
    int iterations = 100000;

    encrypt(state, roundKeys); // Warm-up to mitigate cold start effects

    start = __rdtscp(&ui);

    for (int i = 0; i < iterations; i++) {
        encrypt(state, roundKeys);
    }

    end = __rdtscp(&ui);

    unsigned long long totalCycles = end - start;
    printf("Total cycles for %d blocks: %llu\n", iterations, totalCycles);
    printf("Average cycles per block: %llu\n", totalCycles / iterations);
    printf("Cycles per byte (CpB): %.2f\n", (double)(totalCycles / iterations) / 16);
}

